-- Signal Lost leaderboard, first schema.
--
-- Two tables, and the important decision is in the second one: every run is
-- kept, not only a player's best. Storing the best score as a column means
-- keeping it correct on every write, and loses the history that makes the
-- rest of it interesting. "Best" is a question to ask the data, so it is a
-- query rather than a column.
--
-- The SQL is deliberately plain so one migration serves both H2 (tests and
-- local runs) and PostgreSQL (deployment).

CREATE TABLE player (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(40) NOT NULL,
    first_seen   TIMESTAMP   NOT NULL,
    CONSTRAINT uq_player_display_name UNIQUE (display_name)
);

CREATE TABLE run (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id    BIGINT       NOT NULL,
    level_name   VARCHAR(40)  NOT NULL,

    -- The submission itself, kept so a result can be re-checked later or
    -- replayed for a spectator. It is also the only part the client authored.
    moves        VARCHAR(1000) NOT NULL,

    -- Everything below was computed on the server by replaying those moves.
    stars        INTEGER      NOT NULL,
    turns        INTEGER      NOT NULL,
    par          INTEGER      NOT NULL,
    sightings    INTEGER      NOT NULL,

    submitted_at TIMESTAMP    NOT NULL,

    CONSTRAINT fk_run_player FOREIGN KEY (player_id) REFERENCES player (id),
    CONSTRAINT ck_run_stars CHECK (stars BETWEEN 0 AND 3),
    CONSTRAINT ck_run_turns CHECK (turns >= 0),
    CONSTRAINT ck_run_sightings CHECK (sightings >= 0)
);

-- The leaderboard reads runs for one level, best first. Ordering the index the
-- same way the query does lets it be answered from the index alone.
CREATE INDEX idx_run_leaderboard ON run (level_name, stars DESC, turns ASC);

-- "Every run by this player" is the other access pattern, for a profile page.
CREATE INDEX idx_run_player ON run (player_id, level_name);
